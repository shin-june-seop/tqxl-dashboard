-- TQQQ / SOXL Dashboard V2
-- Run this entire script in Supabase SQL Editor.

create table if not exists public.accounts (
  etf text primary key check (etf in ('TQQQ','SOXL')),
  shares numeric not null default 0,
  avg_cost numeric not null default 0,
  cash numeric not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  trade_date date not null,
  etf text not null check (etf in ('TQQQ','SOXL')),
  side text not null check (side in ('매수','매도')),
  shares numeric not null default 0,
  price numeric not null default 0,
  amount numeric not null default 0,
  stage text,
  reason text,
  memo text,
  created_at timestamptz not null default now()
);

create index if not exists trades_trade_date_idx on public.trades (trade_date desc);
create index if not exists trades_etf_idx on public.trades (etf);

create table if not exists public.snapshots (
  id bigint generated by default as identity primary key,
  snapshot_date date not null,
  etf text not null check (etf in ('TQQQ','SOXL')),
  market_ticker text not null,
  market_price numeric,
  market_200ma numeric,
  market_dist numeric,
  etf_price numeric,
  etf_200ma numeric,
  etf_dist numeric,
  stage integer,
  stage_name text,
  target_pct numeric,
  cash_pct numeric,
  emergency integer,
  bubble boolean default false,
  reason text,
  action text,
  created_at timestamptz not null default now(),
  unique (snapshot_date, etf)
);

create index if not exists snapshots_date_idx on public.snapshots (snapshot_date desc);
create index if not exists snapshots_etf_idx on public.snapshots (etf);

insert into public.accounts (etf, shares, avg_cost, cash)
values ('TQQQ', 0, 0, 0), ('SOXL', 0, 0, 0)
on conflict (etf) do nothing;

